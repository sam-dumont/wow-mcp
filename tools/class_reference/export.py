"""Writes data/class-reference.json: per class, the class trainers (who,
where, which side), what they teach at each level (spell, rank, cost, the
rank it replaces, the races it is for) and Forever's talent names, so the
class guide (wowstats.classguide) can say "Train Mind Blast (Rank 2) at
level 16: High Priestess Laurena, Stormwind City 49.5, 44.6, 18s" for any
character, and its tests can check the guide's talent picks against the
current trees without the network.

Two sources, read as they ship:

- A Polestar release checkout (GPL-3.0): its class trainers
  (addon/Polestar/Core/ClassTrainers.lua, generated by `forge data trainers`:
  capital and starting-town trainers, verified against the Forever
  TrinityCore world database's spawns) and its class training lists
  (addon/Polestar/QoL/ClassSpells.lua, generated by `forge data classspells`
  from the Forever TrinityCore extract's sniffed trainer lists, GPL-2.0, used
  as facts): "<level>=<spell>:<cost>:<rank>[:<previous rank>[:<race mask>]]".
  Zone names from the guides' names table, as tools/trainers/export.py.
- Forever's client tables on wago.tools (product wowf, the latest build):
  the spell names (SpellName) and the talent trees (wowstats.talents'
  catalog: TraitTree and the tables it joins). The sniffed lists miss a few
  training levels (Druid 8 to 14, Shaman 4); those come from the client's
  class abilities (SkillLineAbility, learned from a trainer) at their level
  (SpellLevels), without a price (`cost_copper` null, `from` "client"), less
  passives, talents and what a class quest teaches.

Nothing here comes from a website's text. The same inputs give the same bytes:

    git clone --depth 1 --branch v0.4.1.1 https://github.com/fitzforge/polestar /tmp/polestar
    uv run python tools/class_reference/export.py --polestar /tmp/polestar
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import re
import subprocess
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools" / "trainers"))

from export import zone_names  # noqa: E402 - tools/trainers/export.py

OUT = ROOT / "data" / "class-reference.json"
CLASSES = ("WARRIOR", "PALADIN", "HUNTER", "ROGUE", "PRIEST", "SHAMAN", "MAGE", "WARLOCK", "DRUID")
TRAINER = re.compile(r'\{ npc = (\d+), npcName = "((?:[^"\\]|\\.)*)", map = (\d+), x = ([\d.]+), y = ([\d.]+)'
                     r'.*?faction = "(A|H|AH)", classes = \{ ([^}]*) \} \}')
CLASS_LINE = re.compile(r'^\t(\w+) = "([^"]*)",?$', re.M)


def trainers(lua: str, zones: dict[int, str]) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {c: [] for c in CLASSES}
    for m in TRAINER.finditer(lua):
        t = {"npc": int(m[1]), "name": m[2].replace('\\"', '"'), "map": int(m[3]), "x": float(m[4]),
             "y": float(m[5]), "side": m[6], "zone": zones.get(int(m[3]))}
        for c in re.findall(r'"(\w+)"', m[7]):
            if c in out:
                out[c].append(t)
    return {c: sorted(ts, key=lambda t: (t["map"], t["npc"])) for c, ts in out.items()}


def spells(lua: str) -> dict[str, dict[str, list[dict]]]:
    """{class: {level: [{id, rank, cost_copper, prev, races}]}} from ClassSpells.lua."""
    out: dict[str, dict[str, list[dict]]] = {}
    for cls, body in CLASS_LINE.findall(lua):
        levels: dict[str, list[dict]] = {}
        for part in body.split(";"):
            lvl, _, entries = part.partition("=")
            rows = []
            for e in entries.split(","):
                f = e.split(":")
                rows.append({"id": int(f[0]), "cost_copper": int(f[1]), "rank": int(f[2]),
                             "prev": int(f[3]) if len(f) > 3 and f[3] else None,
                             "races": int(f[4]) if len(f) > 4 and f[4] else 0})
            levels[str(int(lvl))] = rows
        out[cls] = levels
    return out


def wago_rows(table: str, build: str) -> list[dict]:
    from wowstats.upstream import WAGO_URL, fetch

    body = fetch(f"{WAGO_URL}/db2/{table}/csv?build={urllib.parse.quote(build)}", timeout=180)
    if not body:
        raise SystemExit(f"wago.tools has no {table} for {build}")
    return list(csv.DictReader(io.StringIO(body.decode("utf-8"))))


CLASS_BIT = {"WARRIOR": 1, "PALADIN": 2, "HUNTER": 4, "ROGUE": 8, "PRIEST": 16, "SHAMAN": 64, "MAGE": 128,
             "WARLOCK": 256, "DRUID": 1024}
# Taught by a class quest, not bought (the KB's classes lane, classes:druid:19).
QUEST_TAUGHT = {"DRUID": {"Bear Form", "Teleport: Moonglade", "Cure Poison", "Aquatic Form", "Cat Form"}}


def fill_gaps(by_class: dict, build: str, tal: dict) -> list[str]:
    """Training levels the sniffed lists don't have (an even level from 2 to
    60 with nothing on it), from the client's class abilities at that level."""
    sla = [r for r in wago_rows("SkillLineAbility", build) if r["AcquireMethod"] == "0"]
    level = {r["SpellID"]: int(r["SpellLevel"] or r["BaseLevel"] or 0)
             for r in wago_rows("SpellLevels", build) if r["DifficultyID"] == "0"}
    names = {r["ID"]: r["Name_lang"] for r in wago_rows("SpellName", build)}
    added = []
    for cls, bit in CLASS_BIT.items():
        lv = by_class.setdefault(cls, {})
        gaps = [n for n in range(2, 61, 2) if str(n) not in lv]
        if not gaps:
            continue
        mine = [r for r in sla if int(r["ClassMask"] or 0) & bit]
        talent_spells = {str(t["spell"]) for t in tal.get(cls, {}).values()}
        have = {str(r["id"]) for rows in lv.values() for r in rows}
        skip = QUEST_TAUGHT.get(cls, set())
        for n in gaps:
            rows = []
            for sid in sorted({r["Spell"] for r in mine if level.get(r["Spell"]) == n}, key=int):
                name = names.get(sid) or ""
                if not name or sid in have or sid in talent_spells or "(Passive" in name or name in skip:
                    continue
                rows.append({"id": int(sid), "cost_copper": None, "rank": None, "prev": None, "races": 0,
                             "name": name, "from": "client"})
            if rows:
                lv[str(n)] = rows
                added += [f"{cls} {n} {r['name']}" for r in rows]
        _ranks(lv)
        by_class[cls] = dict(sorted(lv.items(), key=lambda kv: int(kv[0])))
    return added


def _ranks(lv: dict) -> None:
    """The client's tables don't link ranks (SupercedesSpell is 0), the
    trainer lists do: a filled spell's rank is one below the rank that names
    it as its previous one (or below the same spell's next listed rank), and
    its own previous rank is the same name one rank down; a spell no rank
    follows has none (0)."""
    rows = [r for k, rs in lv.items() for r in rs]
    level = {r["id"]: int(k) for k, rs in lv.items() for r in rs}
    after = {r["prev"]: r for r in rows if r.get("prev")}
    for _ in range(20):
        changed = False
        for r in rows:
            nxt = after.get(r["id"]) or min(
                (x for x in rows if x["name"] == r["name"] and level[x["id"]] > level[r["id"]]),
                key=lambda x: level[x["id"]], default=None)
            if r["rank"] is None and nxt and nxt["rank"] is not None:
                if not nxt.get("prev"):
                    nxt["prev"] = r["id"]
                r["rank"], changed = max(1, nxt["rank"] - 1), True
                below = [x for x in rows if x["name"] == r["name"] and x["rank"] == r["rank"] - 1]
                if below:
                    r["prev"] = below[0]["id"]
                    after[below[0]["id"]] = r
        if not changed:
            break
    for r in rows:
        if r["rank"] is None:
            r["rank"] = 0


def talent_names(cat: dict) -> dict[str, dict[str, dict]]:
    """{class: {talent name: {tree, max, row, col, spell, needs}}} from the
    talent catalog; `needs` is the talent an arrow comes from (TraitEdge),
    which must be maxed first."""
    out: dict[str, dict[str, dict]] = {}
    names = cat.get("spells") or {}
    for tr in cat.get("trees") or []:
        if tr.get("kind") != "class":
            continue
        got = out.setdefault(tr["class"], {})
        for sec in tr["sections"]:
            at = {}
            for nd in sec["nodes"]:
                if not nd.get("spells"):
                    continue
                n = (names.get(nd["spells"][0]) or {}).get("name")
                if n:
                    at[(nd["col"], nd["row"])] = n
                    got[n] = {"tree": sec["name"], "max": nd["max"], "row": nd["row"], "col": nd["col"],
                              "spell": int(nd["spells"][0]), "needs": None}
            for e in sec.get("edges") or []:
                a, b = at.get((e["fc"], e["fr"])), at.get((e["tc"], e["tr"]))
                # Arrows point down or sideways; the table also holds a few
                # upward twins of real arrows (Bestial Wrath to Intimidation,
                # Nature's Splendor to Nature's Majesty), which would make
                # each talent need the other.
                if a and b and e["tr"] >= e["fr"]:
                    got[b]["needs"] = a
        out[tr["class"]] = dict(sorted(got.items()))
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--polestar", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    root = a.polestar
    from wowstats import talents

    cat_obj = talents.shared()
    cat = cat_obj.get()
    if not cat:
        raise SystemExit("no talent catalog: wago.tools unreachable?")
    build = cat_obj.build
    guides = (root / "addon" / "Polestar_Guides" / "Guides.lua").read_text(encoding="utf-8")
    zones = zone_names(guides)
    by_class = spells((root / "addon" / "Polestar" / "QoL" / "ClassSpells.lua").read_text(encoding="utf-8"))
    want = {str(r["id"]) for lv in by_class.values() for rows in lv.values() for r in rows}
    want |= {str(r["prev"]) for lv in by_class.values() for rows in lv.values() for r in rows if r["prev"]}
    names = {r["ID"]: r["Name_lang"] for r in wago_rows("SpellName", build) if r["ID"] in want}
    # A spell the client no longer has (Blessing of Light and Salvation:
    # Forever removed them) is not taught, whatever the sniffed list says.
    gone = []
    for cls, lv in by_class.items():
        for level, rows in lv.items():
            for r in rows:
                r["name"] = names.get(str(r["id"]))
            gone += [f"{cls} {level} {r['id']}" for r in rows if not r["name"]]
            lv[level] = [r for r in rows if r["name"]]
        by_class[cls] = {k: v for k, v in lv.items() if v}
    tag = subprocess.run(["git", "-C", str(root), "describe", "--tags", "--always"], capture_output=True,
                         text=True).stdout.strip()
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True,
                            text=True).stdout.strip()
    ts = trainers((root / "addon" / "Polestar" / "Core" / "ClassTrainers.lua").read_text(encoding="utf-8"), zones)
    tal = talent_names(cat)
    filled = fill_gaps(by_class, build, tal)
    doc = {
        "schema": 1,
        "source": {"polestar": {"tag": tag, "commit": commit, "licence": "GPL-3.0",
                                "files": ["addon/Polestar/Core/ClassTrainers.lua", "addon/Polestar/QoL/ClassSpells.lua",
                                          "addon/Polestar_Guides/Guides.lua"]},
                   "client": {"build": build, "product": "wowf",
                              "tables": ["SpellName", "SkillLineAbility", "SpellLevels", *talents.TABLES]},
                   "note": "trainers and training lists: Forever's (sniffed TrinityCore data, as Polestar ships "
                           "them); costs in copper before reputation discounts; names and talents from the "
                           "client build above; a level the lists miss from the client's class abilities, "
                           "marked from: client, no cost"},
        "classes": {c: {"trainers": ts[c], "spells": by_class.get(c, {}), "talents": tal.get(c, {})}
                    for c in CLASSES},
        "zones": {str(k): v for k, v in sorted(zones.items())},
    }
    a.out.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for c in CLASSES:
        n = sum(len(v) for v in by_class.get(c, {}).values())
        print(f"{c}: {len(ts[c])} trainers, {n} spells, {len(tal.get(c, {}))} talents")
    if filled:
        print(f"from the client, levels the trainer lists miss: {', '.join(filled)}")
    if gone:
        print(f"left out, not in client {build}: {', '.join(gone)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
