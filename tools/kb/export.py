#!/usr/bin/env python3
"""Builds data/kb-reference.json.gz, the analysis knowledge base's packaged
part, from a Polestar release checkout (GPL-3.0, like this repo):

- forever-db (Polestar's open quest database, GPL-3.0 with CC-BY parts:
  its NOTICE.md): quests, NPCs, items and where items come from, map frames;
- Polestar's own texts about the game, quoted as they are: the header notes
  of its Forever guides (leveling and professions), its dungeon runs
  (data/dungeon-runs.json), its time model (docs/forge/model.md), the
  rested-XP constants it uses (Alts/Snapshot.lua) and its campfire and
  sleeping-bag notes (QoL/Rest.lua).

Nothing here comes from a website. Spells, zones and talents are read at run
time from Forever's own client tables on wago.tools (wowstats.analysis.kb).
The same checkout always gives the same bytes.

    git clone --depth 1 --branch v0.4.3 https://github.com/fitzforge/polestar /tmp/polestar
    python3 tools/kb/export.py --polestar /tmp/polestar
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "data" / "kb-reference.json.gz"
MAX_SOURCES = 12
RANK = {0: "normal", 1: "elite", 2: "rare elite", 3: "boss", 4: "rare"}
SIDE = {0: "both", 1: "Alliance", 2: "Horde"}


def jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def header_comment(text: str) -> tuple[str | None, str]:
    """The guide's title line and its leading comment block (the notes)."""
    title = None
    notes: list[str] = []
    for line in text.splitlines():
        if line.startswith("title "):
            title = line[6:].strip()
        if line.startswith("# Generated by") or line.startswith("# Forge's route search") or \
                line.startswith("# Fixes go into") or line.startswith("# into this file"):
            continue
        if line.startswith("#"):
            notes.append(line.lstrip("#").strip())
        elif line.strip().startswith("step") or line.strip().startswith("goal"):
            break
    return title, "\n".join(notes).strip()


def sections(md: str, names: tuple[str, ...]) -> dict[str, str]:
    out, cur, buf = {}, None, []
    for line in md.splitlines():
        m = re.match(r"^#{2,3} (.+)$", line)
        if m:
            if cur:
                out[cur] = "\n".join(buf).strip()
            cur = m.group(1).strip() if m.group(1).strip() in names else None
            buf = []
        elif cur:
            buf.append(line)
    if cur:
        out[cur] = "\n".join(buf).strip()
    return out


def objective(o: dict, who) -> str:
    kind = o.get("kind")
    prefix = f"{kind} " if kind not in ("item", "object") else ""
    target = who(OBJ_KIND.get(kind, kind), o["target"]) if o.get("target") else ""
    return f"{prefix}{target} x{o.get('count', 1)}"


OBJ_KIND = {"kill": "npc", "item": "item", "object": "object"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--polestar", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    ps = a.polestar
    fdb = ps / "forever-db"
    idx = json.loads((fdb / "index.json").read_text())
    # checkout.py links addon/ to the tagged checkout when forever-db uses its own release.
    addon = (ps / "addon").resolve()
    try:
        tag = subprocess.run(["git", "-C", str(addon), "describe", "--tags", "--exact-match"], capture_output=True, text=True,
                             check=True).stdout.strip()
        commit = subprocess.run(["git", "-C", str(addon), "rev-parse", "HEAD"], capture_output=True, text=True,
                                check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        raise SystemExit(f"no tagged Polestar checkout for {addon}") from e
    fdb_src = f"forever-db {idx.get('version')} (Polestar {tag}, client {idx.get('clientBuild')}), GPL-3.0"
    ps_src = f"Polestar {tag} ({commit[:12]}), GPL-3.0"
    date = idx.get("version", "")
    docs: list[dict] = []

    def doc(id_, kind, title, body, source, label="game data"):
        docs.append({"id": id_, "kind": kind, "title": title, "body": body.strip(), "source": source,
                     "date": date, "label": label})

    npc = {r["id"]: r for r in jsonl(fdb / "data" / "npc.jsonl")}
    obj = {r["id"]: r for r in jsonl(fdb / "data" / "object.jsonl")}
    item = {r["id"]: r for r in jsonl(fdb / "data" / "item.jsonl")}
    quest = {r["id"]: r for r in jsonl(fdb / "data" / "quest.jsonl")}
    starts, ends, rewards, objs, steps = (defaultdict(list) for _ in range(5))
    for r in jsonl(fdb / "data" / "quest_start.jsonl"):
        starts[r["quest"]].append(r)
    for r in jsonl(fdb / "data" / "quest_end.jsonl"):
        ends[r["quest"]].append(r)
    for r in jsonl(fdb / "data" / "quest_reward.jsonl"):
        rewards[r["quest"]].append(r)
    for r in jsonl(fdb / "data" / "quest_objective.jsonl"):
        objs[r["quest"]].append(r)
    for r in jsonl(fdb / "data" / "step.jsonl"):
        steps[r["quest"]].append(r)
    src_of = defaultdict(list)
    for r in jsonl(fdb / "data" / "item_source.jsonl"):
        src_of[r["item"]].append(r)
    reward_of = defaultdict(list)
    for q, rs in rewards.items():
        for r in rs:
            if r["kind"] in ("item", "choice"):
                reward_of[r["id"]].append(q)

    def who(kind, id_):
        if kind == "npc":
            n = npc.get(id_)
            return f"NPC {id_} {n.get('name')}" if n else f"NPC {id_}"
        if kind == "object":
            o = obj.get(id_)
            return f"object {id_} {o.get('name')}" if o else f"object {id_}"
        if kind == "item":
            i = item.get(id_)
            return f"item {id_} {i.get('name')}" if i else f"item {id_}"
        return f"{kind} {id_}"

    for i, n in sorted(npc.items()):
        if not n.get("name"):
            continue
        lv = n.get("level_min"), n.get("level_max")
        body = (f"NPC {i}: {n['name']}" + (f" <{n['subname']}>" if n.get("subname") else "")
                + f". Level {lv[0]}" + (f"-{lv[1]}" if lv[1] != lv[0] else "")
                + f", {RANK.get(n.get('rank'), n.get('rank'))}.")
        doc(f"npc:{i}", "npc", n["name"], body, fdb_src)
    for q, r in sorted(quest.items()):
        if not r.get("title"):
            continue
        side = SIDE.get(r.get("side"), r.get("side"))
        parts = [f"Quest {q}: {r['title']}. Level {r.get('level')}, needs level {r.get('min_level')}, "
                 f"XP {r.get('xp', 'unknown')}, side {side}, area {r.get('zone_area')}."]
        if r.get("money_copper"):
            parts.append(f"Money {r['money_copper']} copper.")
        if starts.get(q):
            parts.append("Starts: " + "; ".join(who(s['kind'], s['id']) for s in starts[q]) + ".")
        if ends.get(q):
            parts.append("Ends: " + "; ".join(who(s["kind"], s["id"]) for s in ends[q]) + ".")
        if objs.get(q):
            parts.append("Objectives: " + "; ".join(objective(o, who) for o in objs[q][:8]) + ".")
        rw = [x for x in rewards.get(q, []) if x["kind"] in ("item", "choice")]
        if rw:
            parts.append("Rewards: " + "; ".join(f"{x['kind']} {who('item', x['id'])}" for x in rw[:8]) + ".")
        for s in steps.get(q, [])[:4]:
            parts.append(f"How ({s.get('action')}): {s.get('text')}")
        doc(f"quest:{q}", "quest", r["title"], " ".join(parts), fdb_src)
    for i, r in sorted(item.items()):
        if not r.get("name"):
            continue
        parts = [f"Item {i}: {r['name']}" + (" (quest item)" if r.get("quest_item") else "") + "."]
        ss = sorted(src_of.get(i, []), key=lambda s: -(s.get("chance") or 0))
        if ss:
            parts.append("Sources: " + "; ".join(
                who(s["kind"], s["id"]) + (f" {s['chance']}%" if s.get("chance") is not None else "")
                for s in ss[:MAX_SOURCES]) + (f" (+{len(ss) - MAX_SOURCES} more)" if len(ss) > MAX_SOURCES else "")
                + ".")
        if reward_of.get(i):
            parts.append("Quest reward of: " + "; ".join(f"quest {q} {quest[q].get('title')}" if q in quest
                                                        else f"quest {q}" for q in reward_of[i][:8]) + ".")
        doc(f"item:{i}", "item", r["name"], " ".join(parts), fdb_src)

    # Polestar's own texts, quoted.
    for g in sorted((ps / "guides" / "forever").rglob("*.guide")):
        rel = g.relative_to(ps / "guides").with_suffix("").as_posix()
        if "/legacy/" in rel:
            continue
        title, notes = header_comment(g.read_text(encoding="utf-8"))
        if len(notes) < 80:
            continue
        doc(f"guide:{rel}", "polestar-guide", f"Guide notes: {title or rel}", notes[:6000],
            f"{ps_src}, guides/{rel}.guide", "quoted")
    dr = json.loads((ps / "data" / "dungeon-runs.json").read_text())
    for r in dr.get("runs", []):
        body = json.dumps({k: r[k] for k in ("dungeon", "faction", "pickups", "run", "handins", "leftOut", "budget")
                           if k in r}, ensure_ascii=False)
        doc(f"dungeon-run:{r['dungeon']}:{r.get('faction')}", "polestar-dungeon",
            f"Polestar's {r['dungeon']} run ({r.get('faction')})", body[:6000], f"{ps_src}, data/dungeon-runs.json",
            "quoted")
    if dr.get("notInRoute"):
        doc("dungeon-run:not-in-route", "polestar-dungeon", "Dungeons Polestar leaves out of the route",
            (dr.get("aboutNotInRoute") or "") + "\n" + json.dumps(dr["notInRoute"], ensure_ascii=False)[:5000],
            f"{ps_src}, data/dungeon-runs.json", "quoted")
    model = (ps / "docs" / "forge" / "model.md").read_text(encoding="utf-8")
    for name, body in sections(model, ("Costs", "Kills", "Grinding", "Quest XP", "Walking",
                                       "Flights, boats and other transport", "Hearth and binds")).items():
        doc(f"polestar-model:{name.lower().replace(' ', '-').replace(',', '')}", "polestar-model",
            f"Polestar's time model: {name}", body[:6000], f"{ps_src}, docs/forge/model.md", "quoted")
    snap = (ps / "addon" / "Polestar" / "Alts" / "Snapshot.lua").read_text(encoding="utf-8")
    m = re.search(r"(-- Classic's rested rules.*?local REST_CAP[^\n]*)", snap, re.S)
    if m:
        doc("polestar:rested-rules", "polestar-code", "Rested XP rules Polestar uses (Classic's numbers)",
            m.group(1), f"{ps_src}, addon/Polestar/Alts/Snapshot.lua", "quoted; Classic Era rules, Forever unverified")
    rest = (ps / "addon" / "Polestar" / "QoL" / "Rest.lua").read_text(encoding="utf-8")
    m = re.search(r"^(-- Boosted Rest status.*?)\n\n", rest, re.S | re.M)
    consts = "\n".join(line for line in rest.splitlines() if re.match(r"^Rest\.(SPELL|BAG) = ", line))
    if m:
        doc("polestar:boosted-rest", "polestar-code", "Boosted Rest (campfire) and the Cozy Sleeping Bag",
            m.group(1) + "\n" + consts, f"{ps_src}, addon/Polestar/QoL/Rest.lua", "quoted")

    ui_map = {r["ui_map"]: [round(abs(r["left"] - r["right"]), 3), round(abs(r["top"] - r["bottom"]), 3)]
              for r in jsonl(fdb / "data" / "ui_map.jsonl")}
    out = {"schema": 1, "polestar": {"tag": tag, "commit": commit}, "forever_db": {k: idx.get(k) for k in (
        "version", "clientBuild", "producerCommit")}, "ui_map": {str(k): v for k, v in sorted(ui_map.items())},
           "docs": docs}
    raw = json.dumps(out, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "wb") as f, gzip.GzipFile(fileobj=f, mode="wb", mtime=0, compresslevel=9) as gz:
        gz.write(raw)
    print(f"{a.out}: {len(docs)} docs, {a.out.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
