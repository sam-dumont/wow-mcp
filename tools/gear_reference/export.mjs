#!/usr/bin/env node
// Polestar's gear data, exported for wow-stats' gear advice (wowstats/gear.py):
// every equippable item's stats, where leveling gear comes from, the stat
// weights per class, spec and level band, and the class rules the scoring
// needs, written to data/gear-reference.json.
//
//   node tools/gear_reference/export.mjs --polestar <checkout> [--out FILE] [--lua BIN]
//
// <checkout> is a clone of fitzforge/polestar at a release tag (the same one
// as tools/route_reference/). Nothing in it is built: tools/gear_reference/dump.lua
// runs the release's own files in an empty Lua environment (no io, os or load):
//
//   - addon/Polestar/Gear/ItemDB.lua, with the data addon Polestar_ItemDB
//     (Items.lua: the Classic Era client's item tables; Forever.lua: Forever's
//     own stats and the leveling sources, generated by Polestar from
//     ForeverLevelingBiS v0.12.0-beta, MIT). Items are parsed by ItemDB.Get,
//     sources by ItemDB.Sources, quests by ItemDB.Quest.
//   - addon/Polestar/Gear/Weights.lua (Polestar's weights and class rules) and
//     SpecData.lua (the level bands, blended with wowsims, MIT; racial traits).
//
// docs/gear-reference.md says what the file holds and whose it is.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));

function args(argv) {
	const o = { out: path.join(HERE, '..', '..', 'data', 'gear-reference.json'), lua: process.env.LUA || 'lua' };
	for (let i = 0; i < argv.length; i++) {
		const k = argv[i];
		if (k === '--polestar') o.polestar = argv[++i];
		else if (k === '--out') o.out = argv[++i];
		else if (k === '--lua') o.lua = argv[++i];
		else throw new Error(`unknown argument ${k}`);
	}
	if (!o.polestar) throw new Error('usage: export.mjs --polestar <checkout> [--out FILE] [--lua BIN]');
	o.polestar = path.resolve(o.polestar);
	return o;
}

// Inventory types gear advice scores (Gear.lua's SLOTS_OF): the rest (shirt,
// tabard, bags, ammo, quivers) never get a score, so they stay out.
const SCORED_INV = new Set([1, 2, 3, 5, 20, 6, 7, 8, 9, 10, 11, 12, 16, 13, 21, 17, 22, 14, 23, 15, 25, 26, 28]);

const list = (v) => (Array.isArray(v) ? v : v && typeof v === 'object' ? Object.values(v) : []);
const byKey = (o) => Object.fromEntries(Object.keys(o).sort((a, b) => Number(a) - Number(b) || (a < b ? -1 : a > b ? 1 : 0)).map((k) => [k, o[k]]));

function main() {
	const o = args(process.argv.slice(2));
	const addon = path.join(o.polestar, 'addon');
	const r = spawnSync(o.lua, [path.join(HERE, 'dump.lua'), addon], { maxBuffer: 1 << 30, encoding: 'utf8' });
	if (r.status !== 0) throw new Error(`${o.lua} dump.lua: ${r.stderr || r.error}`);
	const d = JSON.parse(r.stdout);

	const items = {};
	for (const [id, it] of Object.entries(d.items)) {
		if (!SCORED_INV.has(it.inv)) continue;
		const rec = { inv: it.inv, ilvl: it.ilvl, req: it.req, quality: it.quality, class: it.class, subclass: it.subclass };
		if (it.allow) rec.allow = it.allow;
		if (it.unique) rec.unique = true;
		if (it.speed) rec.speed = it.speed;
		rec.stats = Object.fromEntries(Object.keys(it.stats || {}).sort().map((k) => [k, it.stats[k]]));
		items[id] = rec;
	}
	const sources = {};
	for (const [id, srcs] of Object.entries(d.sources)) {
		if (!items[id]) continue;
		sources[id] = list(srcs).map((s) => {
			if (s.kind === 'quest') return { kind: 'quest', quest: s.quest };
			if (s.kind === 'drop') return { kind: 'drop', npc: s.npc, npc_name: s.npcName ?? null, pct: s.pct, zone: s.zone, zone_name: s.zoneName ?? null };
			return { kind: 'craft', spell: s.spell, profession: s.profession ?? null, skill: s.skill };
		});
	}
	const quests = {};
	for (const [id, q] of Object.entries(d.quests)) {
		quests[id] = { name: q.name ?? null, level: q.level, req: q.req, side: q.side, zone: q.zone,
			zone_name: (q.zone && d.zones[String(q.zone)]) || null, race: q.race, class: q.class, dungeon: q.dungeon,
			choices: list(q.choices), items: list(q.items) };
	}
	const names = {};
	for (const [id, n] of Object.entries(d.names)) if (items[id]) names[id] = n;

	const toc = fs.readFileSync(path.join(addon, 'Polestar', 'Polestar.toc'), 'utf8');
	const version = (toc.match(/^## Version: *(\S+)/m) || [])[1] || null;
	const license = (toc.match(/^## X-License: *(\S+)/m) || [])[1] || null;
	const git = (a) => spawnSync('git', ['-C', o.polestar, ...a], { encoding: 'utf8' }).stdout.trim() || null;
	const meta = d.meta[0] || {};
	const lev = d.leveling || {};
	const out = {
		schema: 1,
		source: `Polestar ${version} gear data (addon/Polestar/Gear, addon/Polestar_ItemDB), read by its own ItemDB.lua`,
		polestar: { version, tag: git(['describe', '--tags', '--exact-match']), commit: git(['rev-parse', 'HEAD']), license },
		item_stats: { source: 'Blizzard Classic Era client tables, as Polestar_ItemDB/Items.lua holds them', build: meta.build ?? null, count: meta.count ?? null },
		leveling: { source: lev.source ?? null, author: 'Thunder', version: lev.version ?? null, generated: lev.generated ?? null, licence: lev.licence ?? null, items: lev.items ?? null, quests: lev.quests ?? null },
		weights: { source: 'Polestar Weights.lua, level bands of SpecData.lua (blended with wowsims, MIT)' },
		gear: d.gear,
		items: byKey(items),
		names: byKey(names),
		sources: byKey(sources),
		quests: byKey(quests),
	};
	fs.writeFileSync(o.out, JSON.stringify(out) + '\n');
	process.stdout.write(`${path.relative(process.cwd(), o.out)}: ${Object.keys(items).length} items, ${Object.keys(sources).length} with sources, ${Object.keys(quests).length} quests\n`);
}

main();
